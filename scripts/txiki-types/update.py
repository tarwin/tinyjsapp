#!/usr/bin/env python3
"""Regenerates template/types/tjs.d.ts: txiki.js's own type definitions
(@txikijs/types, MIT) for the txiki version tinyjs pins, as ONE file.

    python3 scripts/txiki-types/update.py

Run it whenever TJS_VERSION changes (setup.sh, setup.ps1, release.yml), and
commit the result. New projects get the file from `tinyjs new`, existing ones
from `tinyjs update-project` — no npm on anyone's machine.

Why one file: projects (and update-project) carry a single types/tjs.d.ts.
The package is an index of 13 files: txikijs.d.ts is a MODULE (`declare
global { … } export {}`) and the rest are ambient `declare module 'tjs:x'`
blocks. Ambient module declarations are only legal in a script file — in a
module file TypeScript reads them as augmentations of modules that don't
exist — so the global block is unwrapped and the whole thing is a script.

Standard library only. The tarball is checked against the registry's
published sha512 before anything is read from it.
"""
import base64, hashlib, io, json, re, sys, tarfile, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'template/types/tjs.d.ts'

version = re.search(r'TJS_VERSION="\$\{TJS_VERSION:-v([0-9.]+)\}"',
                    (ROOT / 'setup.sh').read_text()).group(1)

def get(url):
    with urllib.request.urlopen(url, timeout=30) as r:
        return r.read()

meta = json.loads(get(f'https://registry.npmjs.org/@txikijs/types/{version}'))
tgz = get(meta['dist']['tarball'])
algo, want = meta['dist']['integrity'].split('-', 1)
assert algo == 'sha512', meta['dist']['integrity']
if base64.b64encode(hashlib.sha512(tgz).digest()).decode() != want:
    sys.exit(f'@txikijs/types@{version}: tarball does not match the registry integrity hash')

files = {}
with tarfile.open(fileobj=io.BytesIO(tgz)) as tar:
    for m in tar.getmembers():
        if m.isfile() and m.name.startswith('package/src/') and m.name.endswith('.d.ts'):
            files[m.name[len('package/src/'):]] = tar.extractfile(m).read().decode()

# index.d.ts names the files and their order; follow it, so a file the
# package adds later can't be silently left out.
order = re.findall(r'/// <reference path="\./([^"]+)" />', files['index.d.ts'])
missing = set(files) - set(order) - {'index.d.ts'}
assert not missing, f'not referenced from index.d.ts: {missing}'

def unwrap_global(src):
    # `declare global {` … matching `}` , then `export {};` — keep the inside.
    head, sep, rest = src.partition('declare global {')
    assert sep, 'txikijs.d.ts: no `declare global {`'
    rest = rest.rstrip()
    assert rest.endswith('export {};'), 'txikijs.d.ts: expected to end with `export {};`'
    body, tail = rest[:-len('export {};')].rstrip().rsplit('}', 1)
    assert not tail.strip(), f'txikijs.d.ts: unexpected text after the global block {tail.strip()!r}'
    # Inside `declare global` everything is implicitly ambient; at the top of
    # a .d.ts a namespace/class/const/function needs its own `declare`
    # (TS1046). The block's members sit at a 4-space indent.
    body = re.sub(r'^    (namespace|const|let|var|function|class|abstract class|enum) ',
                  r'    declare \1 ', body, flags=re.M)
    return head + body

parts = []
for name in order:
    src = files[name]
    if name == 'txikijs.d.ts':
        src = unwrap_global(src)
    src = re.sub(r'^/// <reference path="[^"]+" />\n', '', src, flags=re.M)
    assert not re.search(r'^(import|export) ', src, re.M), f'{name}: top-level import/export'
    parts.append(f'// ---- {name} ' + '-' * max(4, 60 - len(name)) + '\n' + src.strip() + '\n')

# The lib reference: txiki's sockets and files are Disposable/AsyncDisposable
# (`using`), which live in TypeScript's esnext.disposable lib — not loaded by
# the es2022 target projects use. It has to come before any statement.
# @ts-nocheck: the file leans on the dom lib's types (Response, ReadableStream,
# console), so a backend with a narrower "lib" got errors in a file the user
# didn't write. 26.6.0's ffi types also failed `strict` (fixed in 26.11.0).
# It only silences checking OF this file; code using the types is still checked.
header = f"""/// <reference lib="esnext.disposable" />
// @ts-nocheck
// txiki.js {version} — the runtime a tinyjs backend runs on.
// Generated by scripts/txiki-types/update.py from @txikijs/types@{version}
// (MIT, Saúl Ibarra Corretgé — https://github.com/saghul/txiki.js); don't
// edit by hand. `tinyjs update-project` refreshes this file.
"""
OUT.write_text(header + '\n' + '\n'.join(parts))
print(f'wrote {OUT.relative_to(ROOT)}: @txikijs/types@{version}, {len(order)} files, {OUT.stat().st_size} bytes')
